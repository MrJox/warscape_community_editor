#!/usr/bin/env python3
"""Writes crates/wce_tile/src/decal_sizes.rs: the most common size of each decal the kit's tiles place (the `scale` of their
ProjectedDecalInstance: across, depth, along; signs dropped), so that a new decal starts at its own size and shape, not at the type's
default (a 12 x 3 m border strip, which stretched every other decal).

    python3 -I scripts/re/decal_sizes.py <kit raw_data/terrain/tiles> crates/wce_tile/src/decal_sizes.rs
"""
import collections, os, re, sys

TAG = re.compile(rb'<ProjectedDecalInstance\s([^>]*)>')
ATTR = re.compile(rb'([A-Za-z_][A-Za-z_0-9]*)="([^"]*)"')
VEC = re.compile(r"vector\(([^,]+),([^,]+),([^)]+)\)")

root, out_path = sys.argv[1], sys.argv[2]
sizes = collections.defaultdict(collections.Counter)
tiles = 0
for d, _, fs in os.walk(root):
    for f in fs:
        if f != "tile.ted":
            continue
        tiles += 1
        for m in TAG.finditer(open(os.path.join(d, f), "rb").read()):
            a = {k.decode(): v.decode() for k, v in ATTR.findall(m.group(1))}
            v = VEC.match(a.get("scale", ""))
            if v and "key" in a:
                sizes[a["key"].lower().replace("/", "\\")][tuple(abs(float(x)) for x in v.groups())] += 1


def num(x):
    s = f"{x:.3f}".rstrip("0")
    return s + "0" if s.endswith(".") else s


out = [f"//! Generated by scripts/re/decal_sizes.py over the {tiles} tile.ted of the Attila assembly kit (2026-11-21): the most common size",
       "//! of each decal the kit places, in the kit's units (metres): across (x), depth (y), along (z). Do not edit: run the script again.",
       "",
       "/// Each decal's key (lower case, backslashes) and its most common size: across, depth, along.",
       "pub const DECAL_SIZES: &[(&str, [f32; 3])] = &["]
for k in sorted(sizes):
    x, y, z = sizes[k].most_common(1)[0][0]
    out.append(f'    (r"{k}", [{num(x)}, {num(y)}, {num(z)}]),')
out += ["];", "",
        "/// The kit's most common size of a decal (across, depth, along; metres), by its key in any case and either slash.",
        "#[must_use]",
        "pub fn decal_size(key: &str) -> Option<[f32; 3]> {",
        "    let key = key.to_lowercase().replace('/', \"\\\\\");",
        "    DECAL_SIZES.iter().find(|(k, _)| *k == key).map(|(_, s)| *s)",
        "}",
        ""]
open(out_path, "w").write("\n".join(out))
