#!/usr/bin/env python3
"""Writes crates/wce_tile/src/instance_templates.rs from instance_defaults.py's summary (scripts/re/instance_defaults.json).

    python3 -I scripts/re/instance_templates.py scripts/re/instance_defaults.json crates/wce_tile/src/instance_templates.rs
"""
import json, sys

# Set when an instance is made (where it is, its shape), not taken from the kit.
PLACED = {"position": "vector(0,0,0)", "orientation": "euler(0,0,0)", "area": "0", "lf_offset": "0"}

d = json.load(open(sys.argv[1]))
out = ["//! Generated by scripts/re/instance_templates.py from scripts/re/instance_defaults.json (scripts/re/instance_defaults.py over the 1380",
       "//! tile.ted of the Attila assembly kit, 2026-10-25): the defaults of a new instance of each type: TEd's attribute order and the most",
       "//! common value of each attribute (where it is and its shape are set when it is made), the wrappers it holds, and its points' attributes.",
       "//! Do not edit: run the scripts again.", "", "/// A new instance's defaults.", "pub struct InstanceTemplate {", "    pub kind: &'static str,",
       "", "    /// The attributes in TEd's order, raw (entity encoded) values.", "    pub attrs: &'static [(&'static str, &'static str)],", "",
       "    /// The wrappers it holds, in order (`children`, `points`); none: a leaf element.", "    pub wrappers: &'static [&'static str],", "",
       "    /// Its points' attributes in order.", "    pub point_attrs: &'static [(&'static str, &'static str)],", "}", "",
       "pub const TEMPLATES: &[InstanceTemplate] = &["]
for kind, v in d.items():
    attrs = ", ".join(f'("{k}", r#"{PLACED.get(k, v["values"][k])}"#)' for k in v["order"])
    wrappers = ", ".join(f'"{w}"' for w in v["shape"])
    points = ", ".join(f'("{k}", r#"{v["point_values"][k]}"#)' for k in v["point_order"])
    out.append(f'    InstanceTemplate {{ kind: "{kind}", attrs: &[{attrs}], wrappers: &[{wrappers}], point_attrs: &[{points}] }},')
out += ["];", "", "/// The defaults of a type.", "pub fn template(kind: &str) -> Option<&'static InstanceTemplate> {",
        "    TEMPLATES.iter().find(|t| t.kind == kind)", "}", ""]
open(sys.argv[2], "w").write("\n".join(out))
